window.freeMolds = window.moldsManifest || [];

/**
 * Obtém um molde pelo ID
 */
function getMoldById(moldId) {
  return window.freeMolds.find((mold) => mold.id === moldId);
}

/**
 * Obtém lista de coleções únicas
 */
function getMoldCollections() {
  return [...new Set(window.freeMolds.map((mold) => mold.collection))].sort();
}

/**
 * Obtém lista de categorias únicas
 */
function getMoldCategories() {
  return [...new Set(window.freeMolds.map((mold) => mold.category))].sort();
}

/**
 * Obtém lista de dificuldades únicas
 */
function getMoldDifficulties() {
  return [...new Set(window.freeMolds.map((mold) => mold.difficulty))];
}

/**
 * Retorna markup da imagem preview do molde
 */
function getMoldPreviewMarkup(mold) {
  if (!mold || !mold.files) {
    return `<img class="mold-preview-image" src="https://www.pixelbeadsbrasil.com.br/assets/images/placeholder-molde.svg" alt="Imagem não disponível" loading="lazy" decoding="async" />`;
  }

  const previewSrc = mold.files.png || mold.files.jpg || mold.files.svg || 'https://www.pixelbeadsbrasil.com.br/assets/images/placeholder-molde.svg';
  const altText = `Molde Hama Beads ${mold.title} da coleção ${mold.collection}`;

  return `
    <img
      class="mold-preview-image"
      src="${previewSrc}"
      alt="${altText}"
      loading="lazy"
      decoding="async"
      onerror="this.onerror=null;this.src='https://www.pixelbeadsbrasil.com.br/assets/images/placeholder-molde.svg'"
    />
  `;
}

/**
 * Retorna HTML dos chips de cores
 */
function getMoldColorChips(mold) {
  if (!mold || !Array.isArray(mold.colors) || mold.colors.length === 0) {
    return '';
  }

  const colorMap = {
    'Preto': '#212121',
    'Verde Bandeira': '#228B22',
    'Verde Claro': '#90EE90',
    'Verde Escuro': '#2F4F2F',
    'Branco': '#FFFFFF',
    'Bege/Pele': '#F5DEB3',
    'Vermelho': '#DC143C',
    'Laranja': '#FF8C00',
    'Amarelo': '#FFD700',
    'Amarelo Claro': '#FFFFE0',
    'Amarelo Escuro/Mostarda': '#8B8000',
    'Cinza': '#808080',
    'Cinza Claro': '#D3D3D3',
    'Cinza Escuro': '#A9A9A9',
    'Azul': '#4169E1',
    'Azul Claro': '#87CEEB',
    'Azul Escuro': '#00008B',
    'Marrom': '#8B4513',
    'Marrom Escuro': '#654321',
    'Marrom Claro': '#D2B48C',
    'Roxo': '#800080',
    'Roxo Escuro': '#4B0082',
    'Roxo Claro': '#DDA0DD',
    'Rosa': '#FFC0CB',
    'Bege': '#F5F5DC',
    'Laranja/Marrom': '#CD853F'
  };

  const displayColors = mold.colors.slice(0, 6);
  let html = '';

  displayColors.forEach(colorName => {
    const hexColor = colorMap[colorName] || '#CCCCCC';
    html += `
      <span class="color-chip" style="background-color: ${hexColor}; border: 1px solid #999;" title="${colorName}"></span>
    `;
  });

  if (mold.colors.length > 6) {
    html += `<span style="font-size: 11px; color: #666; font-weight: 600; margin-left: 3px;">+${mold.colors.length - 6}</span>`;
  }

  return html;
}

